function artGrab(c, W, H, thr) { const d = c.getImageData(0, 0, W, H).data, m = new Uint8Array(W * H); for (let i = 0; i < W * H; i++) m[i] = d[i * 4 + 3] >= thr ? 1 : 0; return m; }
/** Kontur pixelgenau rastern (Kantenglättung wird verworfen → knackige Pixelkanten) */
function artRaster(A, Q, by, W, H, ox, gy) {
  const c = artCanvas(W, H);
  const X = x => ox + x * Q, Y = y => gy - (y * Q + by);
  const trace = cmds => { c.beginPath(); for (const cm of cmds) { if (cm[0] === 'M') c.moveTo(X(cm[1]), Y(cm[2])); else if (cm[0] === 'L') c.lineTo(X(cm[1]), Y(cm[2])); else if (cm[0] === 'Q') c.quadraticCurveTo(X(cm[1]), Y(cm[2]), X(cm[3]), Y(cm[4])); } c.closePath(); };
  c.fillStyle = '#fff'; trace(A.body); c.fill(); const body = artGrab(c, W, H, 128);
  c.clearRect(0, 0, W, H); trace(A.glass); c.fill(); const glass = artGrab(c, W, H, 128);
  return { body, glass };
}
/** Detail-Polygone (gefüllt) oder Linien (stroke = Linienbreite in Sprite-Pixeln) als Maske */
function artPolyMask(polys, Q, by, W, H, ox, gy, stroke) {
  const c = artCanvas(W, H);
  const X = x => ox + x * Q, Y = y => gy - (y * Q + by);
  c.fillStyle = c.strokeStyle = '#fff'; c.lineWidth = stroke || 1; c.lineJoin = 'round';
  for (const p of polys) {
    c.beginPath();
    p.forEach(([x, y], i) => { const px = stroke ? Math.floor(X(x)) + 0.5 : X(x), py = stroke ? Math.floor(Y(y)) + 0.5 : Y(y); if (i) c.lineTo(px, py); else c.moveTo(px, py); });
    if (stroke) c.stroke(); else { c.closePath(); c.fill(); }
  }
  return artGrab(c, W, H, stroke ? 100 : 128);
}
